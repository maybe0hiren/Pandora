#include <QJsonObject>
#include <QString>

#include "Constants.h"

namespace pandora::shared {

enum class PandoraState {
    Active = 0,        ///< Normal operation.
    ShuttingDown = 1,  ///< Shutdown warning issued, countdown running.
    Deactivated = 2    ///< Everything wiped (never persisted).
};

struct Pandora {
    QString id;                       ///< Pandora ID (generated by Security).
    QString keyHash;                  ///< Secure representation of the Pandora Key. Never the raw key.
    QString guardianId;               ///< Node id of the current Guardian.
    int maxNavi = constants::kDefaultMaxNavi;
    qint64 createdAtMs = 0;
    PandoraState state = PandoraState::Active;
    qint64 guardianEpoch = 0;         ///< Incremented on every Guardian change; orders GUARDIAN_CHANGED events.

    bool isValid() const { return !id.isEmpty() && !guardianId.isEmpty(); }

    QJsonObject toJson() const {
        QJsonObject o;
        o.insert(QStringLiteral("id"), id);
        o.insert(QStringLiteral("keyHash"), keyHash);
        o.insert(QStringLiteral("guardianId"), guardianId);
        o.insert(QStringLiteral("maxNavi"), maxNavi);
        o.insert(QStringLiteral("createdAtMs"), static_cast<double>(createdAtMs));
        o.insert(QStringLiteral("state"), static_cast<int>(state));
        o.insert(QStringLiteral("guardianEpoch"), static_cast<double>(guardianEpoch));
        return o;
    }

    static Pandora fromJson(const QJsonObject& o) {
        Pandora p;
        p.id = o.value(QStringLiteral("id")).toString();
        p.keyHash = o.value(QStringLiteral("keyHash")).toString();
        p.guardianId = o.value(QStringLiteral("guardianId")).toString();
        p.maxNavi = o.value(QStringLiteral("maxNavi")).toInt(constants::kDefaultMaxNavi);
        p.createdAtMs = static_cast<qint64>(o.value(QStringLiteral("createdAtMs")).toDouble());
        p.state = static_cast<PandoraState>(o.value(QStringLiteral("state")).toInt());
        p.guardianEpoch = static_cast<qint64>(o.value(QStringLiteral("guardianEpoch")).toDouble());
        return p;
    }
};

}  // namespace pandora::shared
